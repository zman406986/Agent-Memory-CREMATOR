import assert from 'node:assert/strict';
import { test } from 'node:test';
import { RacoonsEngine } from '../src/engine/engine.js';
import { summarize, TranscriptTelemetry } from '../src/engine/telemetry.js';
import type { ForcedLossObservation, MeterReading, TelemetryEvent } from '../src/types/telemetry.js';
import { fixture } from './engine-fixtures.js';

const usage: MeterReading = {
  requestId: 'request-1', revision: 'revision-1', estimatedInputTokens: 1000,
  inputTokens: 1200, outputTokens: 30, cachedInputTokens: null,
  estimateErrorTokens: 200, cachedInputShare: null,
};
const forced: ForcedLossObservation = {
  kind: 'forced-loss', nativeEventId: 'loss-1', turnOrdinal: 2,
  inputTokensBefore: null, inputTokensAfter: 100,
};

/**
 * Every telemetry rule is one whole summary read off a real engine run, so a row
 * builds the run it needs and names every field it expects. A row that pinned one
 * field would let the rest drift: the summary is what the ledger record carries.
 */
const CASES: readonly (readonly [string, () => Promise<void>])[] = [
  ['a committed prune counts removals, generated bytes and recall identities', async () => {
    const name = 'a committed prune counts removals, generated bytes and recall identities';
    const f = await fixture();
    const engine = await RacoonsEngine.open(f.options);
    await engine.process(f.present);
    await engine.process(f.prune);
    const summary = summarize(f.port.live, f.ledger.entries, [usage, forced, forced]);
    assert.equal(summary.removedBytes, f.first.byteLength,
      `row: ${name} — removed bytes are the committed unit's own length`);
    assert.equal(summary.generatedBytes,
      f.port.requests[0]?.application.appendRecords[0]?.bytes.length,
      `row: ${name} — generated bytes are the receipt the host was actually sent`);
    assert.equal(summary.recallIdCount, 1, `row: ${name} — one archive, one recall id`);
    assert.deepEqual(summary.recallIdsIssued, [...f.ledger.recalls.keys()],
      `row: ${name} — the issued ids are the ledger's own, in its order`);
    assert.equal(summary.forcedLossCount, 1, `row: ${name} — the same loss observed twice counts once`);
    assert.equal(summary.tokensAtFirstForcedLoss, 1200,
      `row: ${name} — the first forced loss reads the authoritative input tokens`);
  }],
  ['observe reconciles authoritative usage, deduplicates loss and isolates sink mutation', async () => {
    const name = 'observe reconciles authoritative usage, deduplicates loss and isolates sink mutation';
    const f = await fixture();
    const events: TelemetryEvent[] = [];
    const engine = await RacoonsEngine.open({ ...f.options, onTelemetry: event => events.push(event) });
    engine.observe({ kind: 'usage', requestId: usage.requestId, revision: usage.revision,
      estimatedInputTokens: usage.estimatedInputTokens,
      usage: { inputTokens: 1200, outputTokens: 30, cachedInputTokens: null } });
    engine.observe(forced);
    engine.observe(forced);
    assert.equal(events.filter(event => event.kind === 'usage-reconciled').length, 1,
      `row: ${name} — a reconciled request is emitted once`);
    assert.equal(events.filter(event => event.kind === 'forced-loss').length, 1,
      `row: ${name} — the duplicate loss observation emits nothing`);
    const thrown: TranscriptTelemetry = new TranscriptTelemetry(() => { throw new Error('sink'); });
    assert.doesNotThrow(() => thrown.emit({ kind: 'forced-loss', sessionId: 'session-1', atMs: 1,
      observation: forced }), `row: ${name} — a throwing sink must not fail the caller`);
    thrown.usage(usage);
    thrown.forcedLoss(forced);
    assert.equal(thrown.summarize(f.port.live, []).tokensAtFirstForcedLoss, 1200,
      `row: ${name} — the telemetry object keeps its own record and reads it back`);
  }],
  ['a prepared-only record counts nothing, and forced depth without usage stays unknown', async () => {
    const name = 'a prepared-only record counts nothing, and forced depth without usage stays unknown';
    const f = await fixture();
    const engine = await RacoonsEngine.open(f.options);
    await engine.process(f.present);
    f.port.outcome = 'unknown';
    await engine.process(f.prune);
    const summary = summarize(f.port.live, f.ledger.entries, [forced]);
    assert.equal(summary.removedBytes, 0, `row: ${name} — an uncommitted prepare removes nothing`);
    assert.equal(summary.generatedBytes, 0, `row: ${name} — an uncommitted prepare emits nothing`);
    assert.equal(summary.recallIdCount, 0, `row: ${name} — an uncommitted prepare archives nothing`);
    assert.equal(summary.forcedLossCount, 1, `row: ${name} — the loss itself is still counted`);
    assert.equal(summary.tokensAtFirstForcedLoss, null,
      `row: ${name} — no authoritative usage means the depth is unknown, never guessed`);
  }],
];

test('telemetry accounting — one row per whole summary', async () => {
  for (const [name, run] of CASES) {
    try { await run(); } catch (error) {
      if (error instanceof Error && error.message.startsWith(`row: ${name}`)) throw error;
      throw new Error(`row: ${name} — ${error instanceof Error ? error.message : String(error)}`, { cause: error });
    }
  }
});

test('a negative usage observation is recorded and swallowed, never thrown at the host', async () => {
  const f = await fixture();
  const events: TelemetryEvent[] = [];
  const engine = await RacoonsEngine.open({ ...f.options, onTelemetry: event => events.push(event) });
  assert.doesNotThrow(() => {
    engine.observe({ kind: 'usage', requestId: 'bad-usage', revision: 'revision-1',
      estimatedInputTokens: 10,
      usage: { inputTokens: -1, outputTokens: 0, cachedInputTokens: null } });
  });
  const error = events.find(event => event.kind === 'error');
  assert.ok(error !== undefined, 'the failed reconcile is recorded as error telemetry');
  assert.match(error.message, /inputTokens/);
  assert.equal(events.some(event => event.kind === 'usage-reconciled'), false,
    'a refused reading never reaches the usage record');
});
